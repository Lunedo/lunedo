export function hasIcon(name: string | null | undefined): name is string {
  return typeof name === "string" && Object.hasOwn(ICONS, name);
}

export function icon(name: string, className = ""): Html {
  const node = hasIcon(name) ? ICONS[name] : undefined;
  if (!node) return raw("");
  const children = node
    .map(
      ([tag, attributes]) =>
        `<${tag} ${Object.entries(attributes)
          .map(([key, value]) => `${key}="${escapeHtml(String(value))}"`)
          .join(" ")}/>`,
    )
    .join("");
  const classes = className ? `i ${escapeHtml(className)}` : "i";
  return raw(
    `<svg class="${classes}" viewBox="0 0 24 24" aria-hidden="true" focusable="false">${children}</svg>`,
  );
}
