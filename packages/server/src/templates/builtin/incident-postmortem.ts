function text(t: typeof en): BuiltInTemplateText {
  const timelineRow = () => [placeholder(t.timeHint), placeholder(t.eventHint)];
  return {
    name: t.name,
    description: t.description,
    title: t.title,
    fields: [
      { key: "incident", label: t.incidentLabel, type: "text", required: true },
      { key: "date", label: t.dateLabel, type: "date", required: true },
      { key: "severity", label: t.severityLabel, type: "choice", required: true, options: t.severityOptions },
      { key: "owner", label: t.ownerLabel, type: "person", required: true },
    ],
    document: doc(
      callout("info", paragraph(t.blameless)),
      propertyTable(
        [t.incidentLabel, field("incident")],
        [t.dateLabel, field("date")],
        [t.severityLabel, field("severity")],
        [t.duration, placeholder(t.durationHint)],
        [t.ownerLabel, field("owner")],
        [t.status, status(t.statusDraft, "yellow")],
      ),
      heading(2, t.summary),
      hint(t.summaryHint),
      heading(2, t.impact),
      bulletList(placeholder(t.impactHint)),
      heading(2, t.timeline),
      hint(t.timelineHint),
      table(t.timelineHeaders, timelineRow(), timelineRow(), timelineRow()),
      heading(2, t.rootCause),
      hint(t.rootCauseHint),
      heading(2, t.detection),
      hint(t.detectionHint),
      heading(2, t.wentWell),
      bulletList(placeholder(t.wentWellHint)),
      heading(2, t.wentBadly),
      bulletList(placeholder(t.wentBadlyHint)),
      heading(2, t.lucky),
      bulletList(placeholder(t.luckyHint)),
      heading(2, t.actionItems),
      taskList(placeholder(t.actionItemsHint)),
      heading(2, t.lessons),
      bulletList(placeholder(t.lessonsHint)),
    ),
  };
}

