function text(t: typeof en): BuiltInTemplateText {
  const milestoneRow = () => [
    placeholder(t.milestoneHint),
    placeholder(t.milestoneDescriptionHint),
    placeholder(t.milestoneDateHint),
    status(t.notStarted, "gray"),
  ];
  return {
    name: t.name,
    description: t.description,
    title: t.title,
    fields: [
      { key: "name", label: t.nameLabel, type: "text", required: true },
      { key: "owner", label: t.ownerLabel, type: "person", required: true },
      { key: "startDate", label: t.startDateLabel, type: "date", required: true },
    ],
    document: doc(
      propertyTable(
        [t.nameLabel, field("name")],
        [t.ownerLabel, field("owner")],
        [t.startDateLabel, field("startDate")],
        [t.targetDate, placeholder(t.targetDateHint)],
        [t.status, status(t.statusPlanning, "blue")],
      ),
      heading(2, t.background),
      hint(t.backgroundHint),
      heading(2, t.goals),
      bulletList(placeholder(t.goalsHint)),
      heading(2, t.scope),
      heading(3, t.inScope),
      bulletList(placeholder(t.inScopeHint)),
      heading(3, t.outOfScope),
      bulletList(placeholder(t.outOfScopeHint)),
      heading(2, t.milestones),
      table(t.milestonesHeaders, milestoneRow(), milestoneRow()),
      heading(2, t.team),
      table(
        t.teamHeaders,
        [t.ownerLabel, field("owner"), placeholder(t.responsibilitiesHint)],
        [placeholder(t.roleHint), placeholder(t.personHint), placeholder(t.responsibilitiesHint)],
      ),
      heading(2, t.risks),
      table(t.risksHeaders, [
        placeholder(t.riskHint),
        placeholder(t.levelHint),
        placeholder(t.levelHint),
        placeholder(t.mitigationHint),
      ]),
      heading(2, t.updates),
      hint(t.updatesHint),
    ),
  };
}

