function text(t: typeof en): BuiltInTemplateText {
  const memberRow = () => [placeholder(t.memberHint), placeholder(t.roleHint), placeholder(t.topicsHint)];
  return {
    name: t.name,
    description: t.description,
    title: t.title,
    fields: [{ key: "teamName", label: t.teamNameLabel, type: "text", required: true }],
    document: doc(
      paragraph(t.welcome, field("teamName"), "."),
      heading(2, t.aboutUs),
      hint(t.aboutUsHint),
      heading(2, t.whatWeDo),
      bulletList(placeholder(t.whatWeDoHint)),
      heading(2, t.contact),
      propertyTable(
        [t.chat, placeholder(t.chatHint)],
        [t.email, placeholder(t.emailHint)],
        [t.requests, placeholder(t.requestsHint)],
        [t.hours, placeholder(t.hoursHint)],
      ),
      heading(2, t.members),
      table(t.membersHeaders, memberRow(), memberRow()),
      heading(2, t.priorities),
      orderedList(placeholder(t.prioritiesHint)),
      heading(2, t.workingAgreements),
      hint(t.workingAgreementsHint),
      heading(2, t.links),
      bulletList(placeholder(t.linksHint)),
    ),
  };
}

