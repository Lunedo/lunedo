function text(t: typeof en): BuiltInTemplateText {
  return {
    name: t.name,
    description: t.description,
    title: t.title,
    fields: [
      { key: "feature", label: t.featureLabel, type: "text", required: true },
      { key: "owner", label: t.ownerLabel, type: "person", required: true },
      { key: "status", label: t.statusLabel, type: "choice", required: true, options: t.statusOptions },
    ],
    document: doc(
      propertyTable(
        [t.featureLabel, field("feature")],
        [t.ownerLabel, field("owner")],
        [t.statusLabel, field("status")],
        [t.stakeholders, placeholder(t.stakeholdersHint)],
        [t.release, placeholder(t.releaseHint)],
      ),
      heading(2, t.background),
      hint(t.backgroundHint),
      heading(2, t.goals),
      table(t.goalsHeaders, [placeholder(t.goalHint), placeholder(t.metricHint), placeholder(t.targetHint)]),
      heading(2, t.userStories),
      table(t.userStoriesHeaders, [
        "1",
        placeholder(t.userStoryHint),
        placeholder(t.importanceHint),
        placeholder(t.notesHint),
      ]),
      heading(2, t.requirements),
      table(t.requirementsHeaders, [
        "R1",
        placeholder(t.requirementHint),
        placeholder(t.priorityHint),
        placeholder(t.acceptanceHint),
      ]),
      heading(2, t.design),
      hint(t.designHint),
      heading(2, t.outOfScope),
      bulletList(placeholder(t.outOfScopeHint)),
      heading(2, t.questions),
      table(t.questionsHeaders, [
        placeholder(t.questionHint),
        placeholder(t.answerHint),
        placeholder(t.answeredByHint),
      ]),
    ),
  };
}

